jest.mock('../models', () => ({
  AuditLog: { create: jest.fn() },
  Product: { find: jest.fn() },
  Settings: { findOne: jest.fn() },
  StockMovement: { aggregate: jest.fn() },
  Vendor: { find: jest.fn() },
  VendorLedger: { find: jest.fn() },
  VendorStatement: { create: jest.fn(), findOne: jest.fn() },
}));

const models = require('../models');
const { periodForToday, runSettlementJob } = require('../services/vendorSettlementJob');

function query(value) {
  const chain = { select: jest.fn(() => chain), sort: jest.fn(() => chain), lean: jest.fn(async () => value) };
  return chain;
}

describe('vendor settlement scheduled job', () => {
  beforeEach(() => {
    jest.clearAllMocks();
    models.Product.find.mockReturnValue(query([]));
    models.VendorLedger.find.mockReturnValue(query([]));
    models.StockMovement.aggregate.mockResolvedValue([]);
    models.VendorStatement.create.mockImplementation(async ([data]) => [{ ...data, _id: 'x', toObject: () => data }]);
  });

  it('computes the closed period only on a cut-off date', () => {
    expect(periodForToday([1, 16], new Date('2026-08-16T05:00:00Z')))
      .toEqual({ startDate: '2026-08-01', endDate: '2026-08-15' });
    expect(periodForToday([1, 16], new Date('2026-09-01T05:00:00Z')))
      .toEqual({ startDate: '2026-08-16', endDate: '2026-08-31' });
    expect(periodForToday([1], new Date('2026-09-01T05:00:00Z')))
      .toEqual({ startDate: '2026-08-01', endDate: '2026-08-31' });
    expect(periodForToday([1, 16], new Date('2026-08-10T05:00:00Z'))).toBeNull();
  });

  it('creates system-audited Draft statements once per vendor period', async () => {
    models.Settings.findOne.mockReturnValue(query({ vendorPayoutCutoffDates: [1, 16] }));
    models.Vendor.find.mockReturnValue(query([{ _id: 'v1' }, { _id: 'v2' }]));
    models.VendorStatement.findOne
      .mockReturnValueOnce(query(null))
      .mockReturnValueOnce(query({ _id: 'existing' }));

    const result = await runSettlementJob(new Date('2026-08-16T05:00:00Z'));

    expect(result).toMatchObject({ created: 1, skipped: 1 });
    expect(models.VendorStatement.create).toHaveBeenCalledTimes(1);
    expect(models.VendorStatement.create.mock.calls[0][0][0]).toMatchObject({
      vendorId: 'v1', status: 'Draft', autoGenerated: true,
    });
    expect(models.AuditLog.create).toHaveBeenCalledWith(expect.objectContaining({
      metadata: expect.objectContaining({ system: true }),
    }));
  });

  it('does nothing off a cut-off date', async () => {
    models.Settings.findOne.mockReturnValue(query({ vendorPayoutCutoffDates: [1, 16] }));
    const result = await runSettlementJob(new Date('2026-08-10T05:00:00Z'));
    expect(result.created).toBe(0);
    expect(models.VendorStatement.create).not.toHaveBeenCalled();
  });
});
