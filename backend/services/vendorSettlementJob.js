const {
  AuditLog, Settings, Vendor, VendorStatement,
} = require('../models');
const { generateStatement, periodBounds } = require('./vendorSettlementService');

const DAY_MS = 24 * 60 * 60 * 1000;

function isoDate(date) {
  return date.toISOString().slice(0, 10);
}

function cutoffInMonth(year, month, day) {
  const lastDay = new Date(Date.UTC(year, month + 1, 0)).getUTCDate();
  return new Date(Date.UTC(year, month, Math.min(day, lastDay)));
}

// Returns the closed period ending the day before today when today is a cut-off date.
function periodForToday(cutoffDates, now = new Date()) {
  const today = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate()));
  const candidates = [];
  [-1, 0].forEach((offset) => {
    const base = new Date(Date.UTC(today.getUTCFullYear(), today.getUTCMonth() + offset, 1));
    cutoffDates.forEach((day) => {
      candidates.push(cutoffInMonth(base.getUTCFullYear(), base.getUTCMonth(), day));
    });
  });
  const isCutoffToday = candidates.some((date) => date.getTime() === today.getTime());
  if (!isCutoffToday) return null;
  const previous = candidates.filter((date) => date < today).sort((a, b) => b - a)[0];
  if (!previous) return null;
  return {
    startDate: isoDate(previous),
    endDate: isoDate(new Date(today.getTime() - DAY_MS)),
  };
}

function statementNumber(vendorId, startDate, endDate) {
  return `VST-${vendorId}-${startDate.replace(/-/g, '')}-${endDate.replace(/-/g, '')}`;
}

async function runSettlementJob(now = new Date()) {
  const settings = await Settings.findOne({ singleton: 'global' }).lean();
  const cutoffDates = settings?.vendorPayoutCutoffDates || [];
  const period = cutoffDates.length ? periodForToday(cutoffDates, now) : null;
  if (!period) return { created: 0, skipped: 0, period: null };

  const { start, end } = periodBounds(period.startDate, period.endDate);
  const vendors = await Vendor.find({ status: { $in: ['Active', 'Suspended'] } }).select('_id').lean();
  let created = 0;
  let skipped = 0;
  for (const vendor of vendors) {
    const exists = await VendorStatement.findOne({
      vendorId: vendor._id, periodStart: start, periodEnd: end,
    }).lean();
    if (exists) {
      skipped += 1;
    } else {
      try {
        const figures = await generateStatement(vendor._id, period.startDate, period.endDate);
        const statement = (await VendorStatement.create([{
          vendorId: vendor._id,
          statementNumber: statementNumber(vendor._id, period.startDate, period.endDate),
          ...figures,
          status: 'Draft',
          autoGenerated: true,
        }]))[0];
        await AuditLog.create({
          action: 'CREATE',
          entity: 'VendorStatement',
          entityId: statement._id,
          after: statement.toObject(),
          metadata: { system: true, job: 'vendor-settlement' },
        });
        created += 1;
      } catch (error) {
        if (error.code !== 11000) throw error;
        skipped += 1;
      }
    }
  }
  return { created, skipped, period };
}

function startSettlementJob(intervalMs = 60 * 60 * 1000) {
  const run = () => runSettlementJob().catch((error) => {
    console.error('Vendor settlement job failed:', error.message);
  });
  run();
  return setInterval(run, intervalMs);
}

module.exports = { periodForToday, runSettlementJob, startSettlementJob };
